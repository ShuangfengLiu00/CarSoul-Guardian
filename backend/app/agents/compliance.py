# 类别 -> 处置动作。refuse=直接拒答；safety_disclaim=给免责与导向（仍不经 LLM）。
COMPLIANCE_ACTIONS = {
    "identity": "refuse",
    "geo": "refuse",
    "data_fraud": "refuse",
    "repair_mislead": "refuse",
    "safety_critical": "safety_disclaim",
}
HARD_REFUSE_CATEGORIES = frozenset(
    c for c, a in COMPLIANCE_ACTIONS.items() if a == "refuse")


def _hit_two_factor(q: str, objs: tuple, acts: tuple) -> bool:
    """双因子命中：对象词与动作词都出现才算。q 需已 lower()。"""
    return any(o.lower() in q for o in objs) and any(a.lower() in q for a in acts)


def _hit_data_fraud(q: str) -> bool:
    """三因子数据造假判定。q 约定为已 lower() 的串。

    因子1 对象词必须命中；因子2 致使类动作词命中即拦；
    因子2' 状态类动作词须再命中因子3 致使框架词才拦。
    """
    if not any(o.lower() in q for o in _KW_FRAUD_OBJ):
        return False
    if any(a.lower() in q for a in _KW_FRAUD_ACT):
        return True
    if any(s.lower() in q for s in _KW_FRAUD_ACT_STATE) and any(
            c.lower() in q for c in _KW_FRAUD_CAUSATIVE):
        return True
    return False


def compliance_hit(query: str) -> Optional[tuple[str, str]]:
    """返回 (类别, 应答文案)；未命中返回 None。

    判定顺序（先严后宽）：
      identity -> geo -> data_fraud -> repair_mislead -> safety_critical

    safety_critical 的第二项是免责声明而非拒答文案，
    调用方须配合 COMPLIANCE_ACTIONS[类别] 判断处置方式。
    """
    q = query.lower()
    if any(k.lower() in q for k in _KW_IDENTITY):
        return ("identity", _REFUSE_IDENTITY)
    if any(k.lower() in q for k in _KW_GEO):
        return ("geo", _REFUSE_GEO)
    if _hit_data_fraud(q) and not any(k.lower() in q for k in _KW_FRAUD_DETECT_INTENT):
        return ("data_fraud", _REFUSE_DATA_FRAUD)
    if _hit_two_factor(q, _KW_HV_OBJ, _KW_HV_ACT):
        return ("repair_mislead", _REFUSE_REPAIR_MISLEAD)
    if _hit_two_factor(q, _KW_SAFETY_PART, _KW_SAFETY_CLEARANCE):
        return ("safety_critical", _SAFETY_CRITICAL_NOTICE)
    return None
